def control_greenhouse_climate(temperature):
    print(f"\n[ДАТЧИК]: Текущая температура в теплице: {temperature}°C")
    
    # Защита от критического перегрева (Кейс 1 июля: +43°C)
    if temperature >= 35:
        status = "⚠️ КРИТИЧЕСКИЙ ПЕРЕГРЕВ! Компьютер открывает форточки на 100% и включает вентиляторы."
    
    # Защита от ночного холода (Кейс 24 июля: +5°C)
    elif temperature <= 12:
        status = "❄️ СЛИШКОМ ХОЛОДНО! Компьютер закрывает окна и запускает ночной обогрев."
    
    # Идеальный микроклимат для стабильного роста огурцов и клубники
    else:
        status = "✅ Температура в норме. Система работает в штатном режиме эко-контроля."
        
    return status

# --- СИМУЛЯЦИЯ РАБОТЫ ПРОГРАММЫ НА ОСНОВЕ ТВОИХ ДАННЫХ ---
# 1. Проверяем день пиковой жары (1 июля)
print(control_greenhouse_climate(43))

# 2. Проверяем холодную ночь (24 июля)
print(control_greenhouse_climate(5))

# 3. Проверяем обычный рабочий день
print(control_greenhouse_climate(25))
